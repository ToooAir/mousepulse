"""Generate src/bat_table.rs from vcc.vaxee.co's bat_paramter.js.

usage: python3 tools/gen_bat_table.py path/to/bat_paramter.js > src/bat_table.rs
"""
import re
import sys

RATES = {"05k": 1, "1k": 2, "2k": 3, "4k": 4, "8k": 5}  # report rate index (cmd 0x07)


def parse(src):
    tables = {}
    for m in re.finditer(r"export const mode(Charging)?Datas(\d+) = \{(.*?)\n\};", src, re.S):
        charging, sensor, body = bool(m.group(1)), int(m.group(2)), m.group(3)
        for mm in re.finditer(r"(gaming|standard): \{(.*?)\n  \}", body, re.S):
            for rm in re.finditer(r"_(\w+k): \{(.*?)\n    \}", mm.group(2), re.S):
                rows = {}
                for e in re.finditer(r"_(\d+): \{ bat: `([^`]*)`, time: `([^`]*)` \}", rm.group(2)):
                    bat = e.group(2).replace("${lang['low_down_text'] ?? ''}", "<")
                    time = e.group(3).replace("${hourString}", "").replace("${powerLowString}", "")
                    rows[int(e.group(1))] = (bat, time)
                assert sorted(rows) == list(range(0, 101, 5)), (sensor, mm.group(1), rm.group(1))
                key = (sensor, charging, mm.group(1) == "standard", RATES[rm.group(1)])
                tables[key] = [rows[p] for p in range(0, 101, 5)]
    return tables


def rust_str(s):
    return '"' + s + '"'


def main():
    tables = parse(open(sys.argv[1], encoding="utf-8").read())
    out = [
        "// Generated by tools/gen_bat_table.py from vcc.vaxee.co bat_paramter.js. Do not edit.",
        "// Rows are indexed by battery step (percent / 5): (battery label, runtime hours).",
        '// An empty hours string means "charge now".',
        "",
        "pub type Row = [(&'static str, &'static str); 21];",
        "",
        "/// Row for (sensor, charging, standard mode, report rate index).",
        "pub fn row(sensor: u16, charging: bool, standard: bool, rate: u8) -> Option<&'static Row> {",
        "    Some(match (sensor, charging, standard, rate) {",
    ]
    for (sensor, charging, standard, rate), rows in sorted(tables.items()):
        cells = ", ".join(f"({rust_str(b)}, {rust_str(t)})" for b, t in rows)
        out.append(f"        ({sensor}, {str(charging).lower()}, {str(standard).lower()}, {rate}) => &[{cells}],")
    out += ["        _ => return None,", "    })", "}", ""]
    print("\n".join(out))


main()
